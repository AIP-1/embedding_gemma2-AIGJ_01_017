# ── 임베딩 검색이 뭔가 ───────────────────────────────────────
# 임베딩 = 문장을 숫자 768개짜리 목록(벡터)으로 바꾼 것. 뜻이 비슷한 문장은 벡터도 비슷한 방향을 가리킨다.
# 두 벡터가 얼마나 비슷한지는 '코사인 유사도'로 잰다. 1에 가까울수록 비슷하고, 0이면 관계없음.
# 검색 = 질의 벡터와 모든 문서 벡터의 유사도를 계산해서 가장 큰 문서를 고르는 것.
# ────────────────────────────────────────────────────────────

import time                   # 파이썬 기본 패키지. 시간을 재는 데 쓴다
from eg2 import load          # 같은 폴더의 eg2.py 에서 load 함수를 가져온다 (2단계에서 만든 공통 로더)

# load() : 인자 없이 부르면 vision=False, audio=False → 텍스트 전용(약 270M 파라미터)으로 GPU에 올린다.
# 처음 부를 때 모델 파일을 읽느라 수십 초 걸린다.
model = load()

# [ ... ] : 리스트. 여러 값을 순서대로 담는 자료형. 0번부터 번호가 붙는다 (docs[0] = 첫 문장).
# 문서 4개: 질의와 관련 있는 것 2개(0번 CO2, 1번 에어컨) + 방해 문장 2개(조도, Jetson)
docs = [
    "환기가 부족하면 강의실 CO2 농도가 1000ppm을 넘어 집중력이 떨어진다.",
    "에어컨 설정 온도는 하계 26도, 동계 20도가 권장된다.",
    "조도가 300lux 미만이면 필기 작업 시 눈의 피로가 커진다.",
    "Jetson Orin Nano는 67 TOPS의 AI 성능을 제공한다.",
]
# 질의 2개. 정답 문서와 겹치는 단어가 거의 없다 → 단어 일치가 아니라 '의미'로 찾는지 보는 시험
queries = ["수업 중에 졸리고 머리가 맑지 않아요", "여름에 냉방 몇 도로 맞춰야 하나요?"]

# model.encode(문장 리스트, ...) : 문장들을 임베딩으로 바꾼다.
#   결과 d 는 numpy 배열(숫자 표). 모양은 (문서 4개, 768) = 4행 768열.
# prompt_name="Document" : 문서용 안내 문구를 앞에 붙여서 임베딩한다.
#   질의는 아래에서 "SearchQuery"를 쓴다. 둘을 구분해야 검색 성능이 제대로 나온다.
# normalize_embeddings=True : 각 벡터의 길이를 1로 맞춘다.
#   길이가 1이면 두 벡터의 내적(곱해서 더한 값)이 곧 코사인 유사도가 되어 계산이 간단해진다.
d = model.encode(docs, prompt_name="Document", normalize_embeddings=True)

# for 변수 in 리스트: → 리스트의 값을 하나씩 꺼내 변수에 넣고, 들여쓴 블록을 반복 실행한다.
# 여기서는 dim = 768, 256, 128 로 세 번 반복한다.
# 왜 줄여 보나: 이 모델은 '마트료시카' 방식으로 학습돼서 벡터의 앞부분만 잘라 써도 뜻이 대부분 남는다.
#             짧을수록 저장 공간과 검색 계산이 줄어든다. 줄여도 정답이 유지되는지 보는 것이 목적.
for dim in [768, 256, 128]:
    t = time.perf_counter()   # 지금 시각(초). 끝난 시각에서 빼면 걸린 시간이 된다

    # 질의 임베딩. truncate_dim=dim : 결과 벡터의 앞쪽 dim개 값만 남긴다.
    # 결과 q 의 모양: (질의 2개, dim)
    q = model.encode(queries, prompt_name="SearchQuery",
                     truncate_dim=dim, normalize_embeddings=True)

    ms = (time.perf_counter() - t) * 1000   # 걸린 시간(초) × 1000 = 밀리초(ms)

    # 슬라이싱 d[:, :dim] : 배열에서 일부를 잘라 낸다. [행, 열] 순서.
    #   ':'    = 전부 → 모든 행(문서 4개)
    #   ':dim' = 0번부터 dim-1번까지 → 앞쪽 dim개 열
    # 문서 벡터도 질의와 같은 길이로 잘라야 비교할 수 있다.
    dd = d[:, :dim]

    # 자른 뒤 재정규화: 잘라 내면 벡터 길이가 1보다 작아지므로 다시 1로 맞춘다.
    #   dd ** 2               : 모든 값을 제곱
    #   .sum(1, keepdims=True): 1번 축(열 방향)으로 더해 문서마다 '제곱합' 하나 → 모양 (4, 1)
    #   ** 0.5                : 제곱근 = 벡터 길이
    #   dd / 길이             : 각 문서 벡터를 자기 길이로 나눔 → 길이 1
    dd = dd / (dd ** 2).sum(1, keepdims=True) ** 0.5

    # @ : 행렬 곱. dd.T 는 dd 를 뒤집은 것(전치, 4×dim → dim×4).
    # q(2×dim) @ dd.T(dim×4) = sim(2×4) : 질의 2개 × 문서 4개의 유사도 표
    #   sim[0][1] = 0번 질의와 1번 문서의 유사도
    sim = q @ dd.T

    # f"...{값}..." : f-string. 중괄호 안의 변수 값을 문자열에 끼워 넣는다.
    #   {ms:.0f} : ms 를 소수점 없이 출력 (예: 35)
    #   \n       : 줄바꿈
    print(f"\n[dim={dim}] {ms:.0f} ms")

    # zip(A, B) : 두 리스트를 짝지어 하나씩 꺼낸다 → (질의0, sim의 0행), (질의1, sim의 1행)
    #   qi  = 질의 문장, row = 그 질의와 문서 4개의 유사도 4개
    for qi, row in zip(queries, sim):
        best = row.argmax()   # argmax() : 가장 큰 값이 몇 번째에 있는지(번호)를 돌려준다
        # docs[best][:25] : 1위 문서 문장의 앞 25글자만 (화면에 길게 안 나오게)
        # {row[best]:.3f} : 1위 유사도를 소수점 셋째 자리까지
        print(f"  {qi} -> {docs[best][:25]}... ({row[best]:.3f})")
